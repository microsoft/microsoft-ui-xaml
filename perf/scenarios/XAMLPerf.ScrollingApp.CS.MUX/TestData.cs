    public class Item : INotifyPropertyChanged
    {
        public Item(string countryOrRegion, string animal, Sightings sightings)
        {
            CountryOrRegion = countryOrRegion;
            Animal = animal;
            Sightings = sightings;
        }

        public string CountryOrRegion { get; }
        public string Animal { get; }
        public Sightings Sightings { get; }
        public uint Count
        {
            get
            {
                return _count;
            }

            set
            {
                if (value != _count)
                {
                    _count = value;

                    PropertyChangedEventHandler handler = PropertyChanged;

                    if (handler != null)
                    {
                        handler.Invoke(this, new PropertyChangedEventArgs("Count"));
                    }
                }
            }
        }

        public event PropertyChangedEventHandler PropertyChanged;

        private uint _count;
    }

