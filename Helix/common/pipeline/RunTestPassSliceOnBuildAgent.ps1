[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [String]$WorkItemProjDir, # Path to proj file containing test workitems generated by GenerateHelixWorkItems.ps1

    [Parameter(Mandatory = $true)]
    [String]$WorkItemProjFileNameFilter, # File name filter for work item proj files

    [Parameter(Mandatory = $true)]
    [String]$TestPayloadDir, # Path to the test binaries

    [Parameter(Mandatory = $true)]
    [String]$UploadRoot, # Logs, screenshots, etc. from the tests will be copied here so they can be uploaded.

    [Parameter(Mandatory = $true)]
    [int]$JobPositionInPhase, # JobPositionInPhase and TotalJobsInPhase determine the selection of work items to run

    [Parameter(Mandatory = $true)]
    [int]$TotalJobsInPhase,

    [int]$RerunPassesRequiredToAvoidFailure = 5,

    # Time limit for each te.exe run, in minutes; 0 turns it off. A healthy work item takes at most about 25 minutes,
    # including reruns, and the 9x rerun loop of one test that keeps timing out can take about 50.
    [double]$TeHangTimeoutMinutes = 60,

    [switch]$SkipCopyTestResultsXml,

    # Code coverage (lab): collect VS static coverage around this slice's te.exe runs.
    # The product DLL(s) in the payload must already be instrumented (see
    # Instrument-CoveragePayload.ps1). Every instrumented module gets its own independent
    # collector/session (auto-discovered from the payload's _coverage-session-id-*.txt files) -
    # there is no shared listener across modules.
    [switch]$CollectCodeCoverage,

    # Path to the coverage tool (Microsoft.CodeCoverage.Console.exe or dotnet-coverage). Auto-resolved if empty.
    [string]$CoverageToolPath = ""
)

# This script is given a proj file generated by GenerateHelixWorkItems.ps1 containing a set of work items to execute.
# Usually these work items are executed by Helix, but in this case we are going to run them directly on the Pipeline agent
# This script is run in parallel across multiple build agents. We choose which items to run based on JobPositionInPhase/TotalJobsInPhase

$ErrorActionPreference = 'Stop'

function Resolve-CoverageTool {
    # Prefer the coverage tool bundled into the payload by Instrument-CoveragePayload.ps1. The lab
    # test agents have neither Visual Studio nor the dotnet CLI, so a co-located copy that rides
    # along in the payload is the only reliable option (and it guarantees the collect engine
    # matches the one that instrumented the DLL). Fall back to a machine-wide dotnet-coverage or
    # VS Console tool if the bundle is missing (e.g. local dev machines).
    $bundled = Join-Path $TestPayloadDir "CoverageTool\Microsoft.CodeCoverage.Console.exe"
    if (Test-Path $bundled) { return $bundled }

    $dc = Get-Command "dotnet-coverage" -ErrorAction SilentlyContinue
    if ($dc) { return $dc.Source }
    $vs = Get-ChildItem -Path @(
        "${env:ProgramFiles}\Microsoft Visual Studio",
        "${env:ProgramFiles(x86)}\Microsoft Visual Studio"
    ) -Recurse -Filter "Microsoft.CodeCoverage.Console.exe" -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($vs) { return $vs.FullName }
    throw "No coverage tool found (bundled payload tool, dotnet-coverage, or Microsoft.CodeCoverage.Console.exe)."
}

Write-Host "WorkItemProjFile = $WorkItemProjFile"
Write-Host "WorkItemProjDir = $WorkItemProjDir"
Write-Host "TestPayloadDir = $TestPayloadDir"
Write-Host "UploadRoot = $UploadRoot"
Write-Host "JobPositionInPhase = $JobPositionInPhase"
Write-Host "TotalJobsInPhase = $TotalJobsInPhase"

if(!(Test-Path $UploadRoot))
{
    mkdir $UploadRoot
}

$dumpsDir = "C:\dumps"
if(!(Test-Path $dumpsDir))
{
    mkdir $dumpsDir
}


# Missing proj dir usually means the upstream CreateTestPayload job didn't publish its payload artifact.
# Fail with a clear message instead of a cryptic Get-ChildItem PathNotFound.
if (-not (Test-Path $WorkItemProjDir))
{
    Throw "Work item proj dir '$WorkItemProjDir' does not exist. The upstream CreateTestPayload job likely did not publish its test-payload artifact (canceled/timed out), so no helix work item proj files were available to run."
}

$projFiles = Get-ChildItem -Path $WorkItemProjDir -Filter $WorkItemProjFileNameFilter

$workItems =@()
foreach($projFile in $projFiles)
{
    [xml]$content = Get-Content $projFile.FullName 
    foreach($item in @($content.Project.ItemGroup.HelixWorkItem))
    {
        if($item)
        {
            $workItems += $item
        }
    }
}

# We choose a 'slice' of work items to run based on JobPositionInPhase/TotalJobsInPhase
$workItemsToRun = @()
$i = $JobPositionInPhase - 1; # JobPositionInPhase starts at 1.
while($i -lt $workItems.Count)
{
    $workItemsToRun += $workItems[$i]
    $i += $TotalJobsInPhase
}

Write-Host "Work items to run:"
$workItemsToRun.Include
Write-Host ""

$testSliceHasWork = $workItemsToRun.Count -gt 0
Write-Host "##vso[task.setvariable variable=TestSliceHasWork]$($testSliceHasWork.ToString().ToLowerInvariant())"
if (-not $testSliceHasWork)
{
    Write-Host "No work items were assigned to this slice. Test result processing will be skipped."
}

$systemCompositionEngineLaunchRequest = $null
$systemCompositionEngineLaunchRequestDirectory = $null
$systemCompositionEngineCrashDumpPolicyState = $null
$systemCompositionEngineCrashDumpPolicyScript = $null

function Move-CrashDumpsToUploadRoot
{
    # Prioritize lifetime-stress dumps and keep enough slots that unrelated
    # dumps in the shared folder do not crowd them out.
    $allDumps = @(Get-ChildItem -Path $dumpsDir -Filter *.dmp)
    $lifetimeDumps = @(
        $allDumps |
            Where-Object { $_.Name -like 'LifetimeStress-*' }
    )
    $otherDumps = @(
        $allDumps |
            Where-Object { $_.Name -notlike 'LifetimeStress-*' }
    )
    $files = @($lifetimeDumps + $otherDumps) | Select-Object -First 10
    foreach($file in $files)
    {
        Move-Item $file.FullName $uploadRoot -Force
    }
}

# -- Code coverage: stand up one collector per instrumented module before this slice's work
# items run. --------------------------------------------------------------------------------
# Every module instrumented by Instrument-CoveragePayload.ps1 wrote its own
# _coverage-session-id-<ModuleStem>.txt discovery file into the payload. We start one
# independent collector per discovered session - separate pipe, separate --output file - so
# e.g. Microsoft.ui.xaml.dll (MUX) and Microsoft.UI.Xaml.Controls.dll (MUXC) never share a
# listener. Each module's collector setup is wrapped in its own try/catch so one module's
# failure doesn't prevent the other module's collector from starting (fail-open per module).
$covSessions = @()
if ($CollectCodeCoverage -and -not $testSliceHasWork)
{
    $CollectCodeCoverage = $false
}
if ($CollectCodeCoverage)
{
    $sidFiles = @(Get-ChildItem -Path $TestPayloadDir -Filter '_coverage-session-id-*.txt' -ErrorAction SilentlyContinue)
    if ($sidFiles.Count -eq 0)
    {
        Write-Host "##vso[task.logissue type=warning]CollectCodeCoverage set but no per-module session id files found under $TestPayloadDir; skipping coverage for this slice."
        $CollectCodeCoverage = $false
    }
}
if ($CollectCodeCoverage)
{
    if (-not $CoverageToolPath) { $CoverageToolPath = Resolve-CoverageTool }

    foreach ($sidFile in $sidFiles)
    {
        $moduleStem = $sidFile.BaseName -replace '^_coverage-session-id-', ''
        $sessionId = (Get-Content $sidFile.FullName -Raw).Trim()
        if (-not $sessionId)
        {
            Write-Host "##vso[task.logissue type=warning]Session id file '$($sidFile.Name)' was empty; skipping coverage for module '$moduleStem' on this slice."
            continue
        }

        $covLog = $null
        $covErrLog = $null
        $collector = $null
        try
        {
            # The session id is freshly generated per module at instrument time, so it is
            # effectively unique per payload build. Even so, a retried/resumed attempt of the
            # SAME build could leave a stale collector's pipe behind. Detect it and opt this
            # module out instead of colliding with (or silently attaching to) another collector
            # (fail-open, consistent with the rest of the coverage path).
            $existingPipe = "\\.\pipe\CodeCoverage.pipe.$sessionId"
            if (Test-Path $existingPipe)
            {
                throw "Coverage pipe '$existingPipe' already exists on this machine - another collector is already using this session id. Skipping coverage for module '$moduleStem' on this slice to avoid cross-contamination."
            }

            $covRawFile = Join-Path $UploadRoot ("coverage-{0}-slice{1}-{2}.coverage" -f $env:COMPUTERNAME, $JobPositionInPhase, $moduleStem)
            Remove-Item $covRawFile -ErrorAction SilentlyContinue
            $covLog = Join-Path $UploadRoot ("_coverage-collector-{0}.log" -f $moduleStem)
            $covErrLog = "$covLog.err"
            Write-Host "Starting coverage collector for '$moduleStem' (session=$sessionId) -> $covRawFile"
            $collector = Start-Process -FilePath $CoverageToolPath `
                -ArgumentList "collect","--session-id",$sessionId,"--server-mode","--output",$covRawFile `
                -PassThru -NoNewWindow -RedirectStandardOutput $covLog -RedirectStandardError $covErrLog
            if ($collector.HasExited)
            {
                throw "Coverage collector for '$moduleStem' exited immediately (exit code=$($collector.ExitCode))."
            }

            $pipePath = "\\.\pipe\CodeCoverage.pipe.$sessionId"
            $pipeReady = $false
            $pipeWaitDeadline = (Get-Date).AddSeconds(30)
            while ((Get-Date) -lt $pipeWaitDeadline)
            {
                if (Test-Path $pipePath)
                {
                    $pipeReady = $true
                    break
                }
                if ($collector.HasExited)
                {
                    throw "Coverage collector for '$moduleStem' exited before pipe '$pipePath' appeared (exit code=$($collector.ExitCode))."
                }
                Start-Sleep -Milliseconds 500
            }
            if (-not $pipeReady)
            {
                throw "Coverage collector pipe '$pipePath' for '$moduleStem' did not appear within 30 seconds."
            }

            # Open the collector pipe so low-integrity te.processhost can connect (else ACCESS_DENIED).
            & (Join-Path $PSScriptRoot "coverage\Set-CoveragePipeAcl.ps1") -SessionId $sessionId

            $covSessions += [pscustomobject]@{
                ModuleStem = $moduleStem
                SessionId  = $sessionId
                RawFile    = $covRawFile
                Collector  = $collector
            }
        }
        catch
        {
            if ($covLog -and (Test-Path $covLog)) { Get-Content $covLog | ForEach-Object { Write-Host "    $_" } }
            if ($covErrLog -and (Test-Path $covErrLog)) { Get-Content $covErrLog | ForEach-Object { Write-Host "    $_" } }
            Write-Host "##vso[task.logissue type=warning]Code coverage collector setup failed for module '$moduleStem'; skipping coverage for this module on this slice. $($_.Exception.Message)"
            if ($collector -and -not $collector.HasExited)
            {
                try { Stop-Process -Id $collector.Id -ErrorAction SilentlyContinue } catch { }
            }
        }
    }

    if ($covSessions.Count -eq 0)
    {
        Write-Host "##vso[task.logissue type=warning]No coverage collectors started successfully; skipping coverage for this slice."
        $CollectCodeCoverage = $false
    }
}

try
{
    if (-not [string]::IsNullOrEmpty($env:COMPOSITION_ENGINE_LAF_TOKEN))
    {
        try
        {
            if ($workItemsToRun.Count -gt 0)
            {
                $setupMarkerPath = Join-Path $TestPayloadDir "setupcomplete.txt"
                if (-not (Test-Path -LiteralPath $setupMarkerPath -PathType Leaf))
                {
                    Throw (
                        "Protected test setup is incomplete. Expected setup marker " +
                        "'$setupMarkerPath' before creating the token-bearing launch request.")
                }

                $repositoryRoot = [IO.Path]::GetFullPath(
                    (Join-Path $PSScriptRoot "..\..\.."))
                $systemCompositionEngineCrashDumpPolicyScript = Join-Path `
                    $repositoryRoot `
                    "build\PipelineScripts\Set-SystemCompositionEngineCrashDumpPolicy.ps1"
                $systemCompositionEngineCrashDumpPolicyState = & $systemCompositionEngineCrashDumpPolicyScript `
                    -ProcessName "te.processhost.exe"
                if ($null -eq $systemCompositionEngineCrashDumpPolicyState)
                {
                    Throw "The token-bearing host crash dump policy was not applied."
                }
                $systemCompositionEngineLaunchRequestDirectory = Join-Path `
                    $TestPayloadDir `
                    "Test\.winui-composition-engine"
                $setLaunchRequestScript = Join-Path `
                    $repositoryRoot `
                    "build\PipelineScripts\Set-SystemCompositionEngineLaunchRequest.ps1"
                $launchRequestParameters = @{
                    LaunchRequestDirectory =
                        $systemCompositionEngineLaunchRequestDirectory
                    NativeManifestPath = Join-Path `
                        $repositoryRoot `
                        "dxaml\test\packages\appx\appxmanifest.native.current.xml"
                    ManagedManifestPath = Join-Path `
                        $repositoryRoot `
                        "dxaml\test\packages\appx\appxmanifest.managed.current.xml"
                }
                $systemCompositionEngineLaunchRequest =
                    & $setLaunchRequestScript @launchRequestParameters
                if ($null -eq $systemCompositionEngineLaunchRequest)
                {
                    Throw "The system composition engine launch request was not created."
                }
            }
        }
        finally
        {
            Remove-Item `
                -LiteralPath Env:\COMPOSITION_ENGINE_LAF_TOKEN `
                -ErrorAction SilentlyContinue
        }
    }

    $hungWorkItems = @()
    foreach($workItem in $workItemsToRun)
    {
        $command = $workItem.Command
        $precommand = $workItem.PreCommands
        $workItemName = $workItem.Include
        $resultsFileName = ".\testResults-$workItemName.xml"
        $workItemUploadRoot = Join-Path $uploadRoot $workItemName
        mkdir $workItemUploadRoot

        $consoleLogOutputFile = Join-Path $workItemUploadRoot "console.log"

        $env:HELIX_CORRELATION_PAYLOAD = $TestPayloadDir
        $env:HELIX_WORKITEM_UPLOAD_ROOT = $workItemUploadRoot
        $env:rerunPassesRequiredToAvoidFailure = $RerunPassesRequiredToAvoidFailure
        $env:HELIX_DUMP_FOLDER = $dumpsDir
        $env:WINUI_TE_HANG_TIMEOUT_MINUTES = $TeHangTimeoutMinutes.ToString([Globalization.CultureInfo]::InvariantCulture)

        Write-Host "Running $workItemName work item"

        # Due to the presence of quotes, symbols, etc. we cannot directly invoke $command from Powershell. So instead we write it to
        # a .cmd file and invoke that.
        $fullCommand = "@echo off`n$precommand`n$command"
        Write-Host $fullCommand
        Out-File -FilePath "temp-runworkitem.cmd" -Encoding ascii -InputObject $fullCommand
        try
        {
            & ./temp-runworkitem.cmd | Tee-Object -file $consoleLogOutputFile
        }
        finally
        {
            Remove-Item -LiteralPath ".\temp-runworkitem.cmd" -Force
        }

        if(!$SkipCopyTestResultsXml)
        {
            if (!(Test-Path ".\testResults.xml"))
            {
                # We expect the work item to produce a 'testResults.xml' file. If it didn't, something bad happened.
                Throw "Expected testResults.xml to be found. Something unexpected happened."
            }

            Move-Item .\testResults.xml $resultsFileName
        }

        # RunHelixWorkItem.ps1 writes TaefHang.txt when the hang watchdog had to end te.exe. Keep going so the rest of
        # the slice still runs, and fail once it has.
        if (Test-Path -LiteralPath (Join-Path $workItemUploadRoot "TaefHang.txt"))
        {
            $hungWorkItems += $workItemName
            Write-Host "##vso[task.logissue type=error]$workItemName hung: te.exe was ended after $TeHangTimeoutMinutes minutes. Its dumps and logs are in the $workItemName folder of this job's test output artifact."
        }

        Get-ChildItem -Path $workItemUploadRoot -Filter *_subresults.json | Move-Item -Destination $uploadRoot
    }

    if ($hungWorkItems.Count -gt 0)
    {
        Throw "te.exe hung in $($hungWorkItems.Count) work item(s) and was ended after $TeHangTimeoutMinutes minutes: $($hungWorkItems -join ', ')"
    }
}
finally
{
    # -- Code coverage: flush this slice's data by shutting every module's collector down. ----
    # This lives in a finally so a failing work item above still flushes whatever coverage was
    # collected and never leaves a collector process running. Each session is shut down
    # independently (own try/catch/finally) so one module's shutdown failure doesn't skip another
    # module's cleanup.
    try
    {
        if ($CollectCodeCoverage -and $covSessions.Count -gt 0)
        {
            foreach ($session in $covSessions)
            {
                try
                {
                    Write-Host "Shutting down coverage collector for '$($session.ModuleStem)' (session=$($session.SessionId))..."
                    # Windows PowerShell 5.1 turns native stderr into a terminating error under
                    # ErrorActionPreference=Stop when it is redirected with 2>&1; relax it for the
                    # call so a chatty shutdown can't abort the flush.
                    $prevErrorActionPreference = $ErrorActionPreference
                    $ErrorActionPreference = 'Continue'
                    try
                    {
                        & $CoverageToolPath shutdown $session.SessionId 2>&1 | Write-Host
                        $shutdownExitCode = $LASTEXITCODE
                    }
                    finally
                    {
                        $ErrorActionPreference = $prevErrorActionPreference
                    }
                    if ($shutdownExitCode -ne 0)
                    {
                        Write-Host "##vso[task.logissue type=warning]Coverage collector shutdown failed for '$($session.ModuleStem)' with exit code $shutdownExitCode (session=$($session.SessionId))."
                    }
                    Start-Sleep -Seconds 5
                    if ((Test-Path $session.RawFile) -and ((Get-Item $session.RawFile).Length -gt 0))
                    {
                        $covMb = [math]::Round((Get-Item $session.RawFile).Length / 1MB, 1)
                        Write-Host "Coverage written for '$($session.ModuleStem)' on this slice: $($session.RawFile) ($covMb MB)"
                    }
                    else
                    {
                        Write-Host "##vso[task.logissue type=warning]No coverage data produced for module '$($session.ModuleStem)' on this slice (session=$($session.SessionId))."
                    }
                }
                catch
                {
                    # Fail-open per module: log and keep going so the remaining collectors are
                    # still shut down and flushed.
                    Write-Host "##vso[task.logissue type=warning]Coverage collector shutdown for '$($session.ModuleStem)' threw (session=$($session.SessionId)); continuing with the remaining modules. $($_.Exception.Message)"
                }
                finally
                {
                    if ($session.Collector -and -not $session.Collector.HasExited)
                    {
                        try { Stop-Process -Id $session.Collector.Id -ErrorAction SilentlyContinue } catch { }
                    }
                }
            }
        }
    }
    finally
    {
        Remove-Item `
            -LiteralPath Env:\COMPOSITION_ENGINE_LAF_TOKEN `
            -ErrorAction SilentlyContinue
        try
        {
            try
            {
                if ($null -ne $systemCompositionEngineLaunchRequest)
                {
                    $systemCompositionEngineLaunchRequest.Dispose()
                }
            }
            finally
            {
                if (-not [string]::IsNullOrEmpty(
                        $systemCompositionEngineLaunchRequestDirectory) -and
                    (Test-Path `
                        -LiteralPath $systemCompositionEngineLaunchRequestDirectory))
                {
                    Remove-Item `
                        -LiteralPath $systemCompositionEngineLaunchRequestDirectory `
                        -Recurse `
                        -Force
                }
            }
        }
        finally
        {
            try
            {
                if ($null -ne $systemCompositionEngineCrashDumpPolicyState)
                {
                    & $systemCompositionEngineCrashDumpPolicyScript `
                        -RestoreState $systemCompositionEngineCrashDumpPolicyState
                }
            }
            finally
            {
                Move-CrashDumpsToUploadRoot
            }
        }
    }
}
